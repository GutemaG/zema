import 'package:drift/drift.dart';
import 'package:drift/native.dart';
import 'package:drift_dev/api/migrations_native.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:zema/app/database/zema_database.dart';

import 'zema/generated/schema.dart';

void main() {
  driftRuntimeOptions.dontWarnAboutMultipleDatabases = true;
  late SchemaVerifier verifier;

  setUpAll(() => verifier = SchemaVerifier(GeneratedHelper()));

  group('ZemaDatabase schema', () {
    test('is version 7', () {
      final db = ZemaDatabase(NativeDatabase.memory());
      addTearDown(db.close);
      expect(db.schemaVersion, 7);
    });

    // Migrations between versions are tested in zema/migration_test.dart,
    // generated by `dart run drift_dev make-migrations`.
    test('the tables match the saved v6 schema dump', () async {
      final connection = await verifier.startAt(6);
      final db = ZemaDatabase(connection);
      addTearDown(db.close);

      await verifier.migrateAndValidate(db, 6);
    });

    test('a fresh database has all twelve tables', () async {
      final connection = await verifier.startAt(7);
      final db = ZemaDatabase(connection);
      addTearDown(db.close);

      final rows = await db
          .customSelect(
            "SELECT name FROM sqlite_master WHERE type = 'table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name",
          )
          .get();

      expect(rows.map((r) => r.read<String>('name')), [
        'cached_songs',
        'catalog_songs',
        'favorites',
        'hidden_folders',
        'hidden_tracks',
        'lyrics_links',
        'play_events',
        'playlist_entries',
        'playlists',
        'queued_reports',
        'tracks',
        'unmatched_entries',
      ]);
    });
  });
}
