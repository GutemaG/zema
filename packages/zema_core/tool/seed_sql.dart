/// Turns the song files in `backend/seed/` (an `index.json` plus LRC files)
/// into `backend/supabase/seed.sql`, which `supabase db reset` loads, and a
/// pgTAP test that the backend serves each song exactly as zema_core reads
/// it. Run `dart run tool/generate_seed_sql.dart` after changing the seed.
library;

import 'dart:convert';

import 'package:zema_core/zema_core.dart';

const seedFolder = 'backend/seed';
const seedSqlPath = 'backend/supabase/seed.sql';
const seedTestPath = 'backend/supabase/tests/database/006_seed.test.sql';

const _statuses = {'draft', 'approved', 'rejected'};

const _header =
    '-- GENERATED by packages/zema_core/tool/generate_seed_sql.dart from\n'
    '-- backend/seed/. Do not edit; change the seed files and run the generator.\n';

/// What [buildSeed] made of the seed folder.
class Seed {
  const Seed(this.songs, this.problems);

  /// Songs that loaded, with their status, in index order.
  final List<(CatalogSong, String)> songs;

  /// Entries that were skipped, and why.
  final List<String> problems;

  String get sql {
    final b = StringBuffer(_header)..writeln();
    for (final (song, status) in songs) {
      b.writeln(
        'select public.seed_song(${_literal(jsonEncode(song.toDocument()))}::jsonb, '
        "'$status');",
      );
    }
    return b.toString();
  }

  String get testSql {
    final b = StringBuffer(_header)
      ..writeln('begin;')
      ..writeln('create extension if not exists pgtap with schema extensions;')
      ..writeln()
      ..writeln('select plan(${songs.length + 1});')
      ..writeln()
      ..writeln('set local role anon;')
      ..writeln();
    for (final (song, status) in songs) {
      final id = song.song.id;
      final expected = status == 'approved'
          ? '${_literal(jsonEncode(song.toDocument()))}::jsonb'
          : 'null::jsonb';
      b.writeln(
        'select is(public.get_song(${_literal(id)}), $expected, '
        '${_literal('$id is served as zema_core reads it')});',
      );
    }
    final approved = [
      for (final (song, status) in songs)
        if (status == 'approved') song.song.id,
    ]..sort();
    b
      ..writeln(
        'select is((select array_agg(id::text order by id collate "C") from public.songs), '
        "${approved.isEmpty ? 'null' : "array[${approved.map(_literal).join(', ')}]"}::text[], "
        "'anon sees exactly the approved seed songs');",
      )
      ..writeln()
      ..writeln('select * from finish();')
      ..writeln('rollback;');
    return b.toString();
  }
}

/// Reads [indexJson] and each entry's file through [readFile]. A malformed
/// entry or file is skipped and listed in [Seed.problems]; the rest load.
Seed buildSeed(String indexJson, String? Function(String file) readFile) {
  final songs = <(CatalogSong, String)>[];
  final problems = <String>[];
  final Object? index;
  try {
    index = jsonDecode(indexJson);
  } on FormatException catch (e) {
    return Seed(const [], ['index.json: ${e.message}']);
  }
  final entries = switch (index) {
    {'songs': final List<Object?> entries} => entries,
    _ => null,
  };
  if (entries == null) return const Seed([], ['index.json: no "songs" list']);
  final ids = <String>{};
  for (final (i, entry) in entries.indexed) {
    final label = switch (entry) {
      {'id': final String id} => id,
      _ => 'entry ${i + 1}',
    };
    if (entry is! Map<String, Object?>) {
      problems.add('$label: not an object');
      continue;
    }
    final file = entry['file'];
    final text = file is String ? readFile(file) : null;
    if (file is String && text == null) {
      problems.add('$label: $file not found');
      continue;
    }
    final status = entry['status'] ?? 'approved';
    if (status is! String || !_statuses.contains(status)) {
      problems.add('$label: unknown status $status');
      continue;
    }
    try {
      final song = importIndexedLrc(entry, text ?? '');
      if (!ids.add(song.song.id)) {
        problems.add('$label: listed twice');
        continue;
      }
      songs.add((song, status));
    } on LyricsFormatFailure catch (e) {
      problems.add('$label: ${e.message}');
    }
  }
  return Seed(songs, problems);
}

String _literal(String text) => "'${text.replaceAll("'", "''")}'";
